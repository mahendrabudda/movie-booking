"""
Synthetic Dataset Generator and Model Trainer for Movie Popularity & Dynamic Pricing.
NOTE: The dataset generated by this script is synthetic and designed to demonstrate
an end-to-end scikit-learn + FastAPI + Spring Boot ML integration for a hackathon MVP.
Model accuracy metrics on this synthetic dataset do not represent real-world box-office performance.
"""

import os
import json
import joblib
import numpy as np
import pandas as pd
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import OneHotEncoder, StandardScaler
from sklearn.compose import ColumnTransformer
from sklearn.pipeline import Pipeline
from sklearn.ensemble import RandomForestClassifier
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import accuracy_score, classification_report

RANDOM_SEED = 42
CLASSES = [
    "FLOP",
    "BELOW_AVERAGE",
    "AVERAGE",
    "HIT",
    "SUPERHIT",
    "BLOCKBUSTER",
    "INDUSTRY_HIT",
]

GENRES = ["ACTION", "SCI_FI", "DRAMA", "THRILLER", "COMEDY", "HORROR", "ROMANCE", "FANTASY"]
LANGUAGES = ["TELUGU", "HINDI", "ENGLISH", "TAMIL", "MALAYALAM", "KANNADA"]


def generate_synthetic_dataset(n_samples: int = 3500, seed: int = RANDOM_SEED) -> pd.DataFrame:
    rng = np.random.default_rng(seed)

    average_rating = np.round(rng.uniform(3.5, 9.8, size=n_samples), 1)
    genre = rng.choice(GENRES, size=n_samples, p=[0.22, 0.15, 0.15, 0.14, 0.12, 0.07, 0.08, 0.07])
    language = rng.choice(LANGUAGES, size=n_samples, p=[0.28, 0.25, 0.20, 0.12, 0.08, 0.07])
    days_since_release = rng.integers(0, 45, size=n_samples)
    movie_duration = rng.integers(95, 195, size=n_samples)
    expected_demand = np.round(rng.uniform(15.0, 100.0, size=n_samples), 1)
    current_occupancy = np.round(rng.uniform(10.0, 99.0, size=n_samples), 1)

    # Construct a deterministic composite score with controlled noise for realistic class separation
    genre_bonus = np.select(
        [genre == "ACTION", genre == "SCI_FI", genre == "FANTASY", genre == "THRILLER"],
        [6.5, 5.5, 4.5, 3.0],
        default=1.0,
    )
    release_freshness = np.maximum(0, (30 - days_since_release) * 0.35)
    duration_factor = np.where((movie_duration >= 125) & (movie_duration <= 175), 2.5, -1.5)
    noise = rng.normal(0, 3.2, size=n_samples)

    composite_score = (
        (average_rating * 6.2)
        + (expected_demand * 0.32)
        + (current_occupancy * 0.34)
        + genre_bonus
        + release_freshness
        + duration_factor
        + noise
    )

    # Map composite score into the 7 popularity categories using percentile-informed thresholds
    labels = []
    for score in composite_score:
        if score < 62.0:
            labels.append("FLOP")
        elif score < 74.0:
            labels.append("BELOW_AVERAGE")
        elif score < 86.0:
            labels.append("AVERAGE")
        elif score < 98.0:
            labels.append("HIT")
        elif score < 109.0:
            labels.append("SUPERHIT")
        elif score < 119.0:
            labels.append("BLOCKBUSTER")
        else:
            labels.append("INDUSTRY_HIT")

    df = pd.DataFrame(
        {
            "averageMovieRating": average_rating,
            "genre": genre,
            "language": language,
            "daysSinceRelease": days_since_release,
            "movieDuration": movie_duration,
            "expectedDemand": expected_demand,
            "currentOccupancy": current_occupancy,
            "popularityCategory": labels,
        }
    )
    return df


def train_and_evaluate():
    base_dir = os.path.dirname(os.path.abspath(__file__))
    data_dir = os.path.join(base_dir, "data")
    model_dir = os.path.join(base_dir, "model")
    os.makedirs(data_dir, exist_ok=True)
    os.makedirs(model_dir, exist_ok=True)

    print("1. Generating reproducible synthetic movie popularity dataset...")
    df = generate_synthetic_dataset(n_samples=3500, seed=RANDOM_SEED)
    csv_path = os.path.join(data_dir, "synthetic_movie_pricing_data.csv")
    df.to_csv(csv_path, index=False)
    print(f"   Saved synthetic dataset ({len(df)} rows) to {csv_path}")
    print("   Class distribution:")
    print(df["popularityCategory"].value_counts().to_string())

    feature_cols = [
        "averageMovieRating",
        "genre",
        "language",
        "daysSinceRelease",
        "movieDuration",
        "expectedDemand",
        "currentOccupancy",
    ]
    X = df[feature_cols]
    y = df["popularityCategory"]

    X_train, X_test, y_train, y_test = train_test_split(
        X, y, test_size=0.20, random_state=RANDOM_SEED, stratify=y
    )

    categorical_features = ["genre", "language"]
    numeric_features = [
        "averageMovieRating",
        "daysSinceRelease",
        "movieDuration",
        "expectedDemand",
        "currentOccupancy",
    ]

    preprocessor = ColumnTransformer(
        transformers=[
            ("num", StandardScaler(), numeric_features),
            ("cat", OneHotEncoder(handle_unknown="ignore"), categorical_features),
        ]
    )

    # Baseline 1: Logistic Regression
    print("\n2. Training Baseline Model (LogisticRegression)...")
    lr_pipeline = Pipeline(
        steps=[
            ("preprocessor", preprocessor),
            ("classifier", LogisticRegression(max_iter=1000, random_state=RANDOM_SEED)),
        ]
    )
    lr_pipeline.fit(X_train, y_train)
    lr_preds = lr_pipeline.predict(X_test)
    lr_acc = accuracy_score(y_test, lr_preds)
    print(f"   LogisticRegression Baseline Accuracy: {lr_acc:.4f}")

    # Primary Model: Random Forest Classifier
    print("\n3. Training Primary Model (RandomForestClassifier)...")
    rf_pipeline = Pipeline(
        steps=[
            ("preprocessor", preprocessor),
            (
                "classifier",
                RandomForestClassifier(
                    n_estimators=220,
                    max_depth=14,
                    min_samples_split=4,
                    random_state=RANDOM_SEED,
                    n_jobs=-1,
                ),
            ),
        ]
    )
    rf_pipeline.fit(X_train, y_train)
    rf_preds = rf_pipeline.predict(X_test)
    rf_acc = accuracy_score(y_test, rf_preds)
    print(f"   RandomForestClassifier Accuracy:      {rf_acc:.4f}")

    print("\n4. Classification Report (RandomForestClassifier):")
    report_str = classification_report(y_test, rf_preds, labels=CLASSES, digits=4)
    print(report_str)

    # Save the best model (RandomForestClassifier pipeline)
    model_path = os.path.join(model_dir, "movie_popularity_model.joblib")
    joblib.dump(rf_pipeline, model_path)
    print(f"5. Saved trained RandomForest pipeline to {model_path}")

    metadata = {
        "modelType": "RandomForestClassifier",
        "baselineModelType": "LogisticRegression",
        "randomSeed": RANDOM_SEED,
        "datasetSamples": len(df),
        "randomForestAccuracy": round(float(rf_acc), 4),
        "logisticRegressionBaselineAccuracy": round(float(lr_acc), 4),
        "features": feature_cols,
        "classes": CLASSES,
        "supportedGenres": GENRES,
        "supportedLanguages": LANGUAGES,
        "disclaimer": (
            "Trained on a reproducible synthetic dataset for demonstrating ML-driven "
            "dynamic ticket pricing integration. Accuracy metrics do not reflect real-world box-office data."
        ),
    }
    meta_path = os.path.join(model_dir, "model_metadata.json")
    with open(meta_path, "w", encoding="utf-8") as f:
        json.dump(metadata, f, indent=2)
    print(f"   Saved model metadata to {meta_path}")


if __name__ == "__main__":
    train_and_evaluate()
